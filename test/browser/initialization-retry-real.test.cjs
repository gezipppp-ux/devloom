const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { randomUUID } = require("node:crypto");
const { execFileSync } = require("node:child_process");
const { chromium } = require("playwright");
const { temporary } = require("../support/helpers.cjs");
const { initializeTestDatabase } = require("../support/database.cjs");
const { SessionManager } = require("../support/session-manager.cjs");
const { FakeClient } = require("../fixtures/web-client.cjs");
const { AccountServices } = require("../../src/application/account-services.cjs");
const { ProjectServices } = require("../../src/application/project-services.cjs");
const { ProjectContentServices } = require("../../src/application/project-content-services.cjs");
const { ProjectDevelopmentServices } = require("../../src/application/project-development-services.cjs");
const { WorkspaceManager } = require("../../src/application/workspace-manager.cjs");
const { projectPermissionCatalog } = require("../../src/domain/project-permissions.cjs");
const { createWebServer } = require("../../src/http/server.cjs");
const { encodeSecret } = require("../../src/storage/database-secrets.cjs");

async function main() {
  const cleanup = [], t = { after: callback => cleanup.push(callback) };
  const root = temporary(t), database = await initializeTestDatabase(t, root);
  let accounts, workspaces, projects, application, browser;
  try {
    accounts = new AccountServices(database);
    const actor = await accounts.create({ username: "retry-admin", password: "fixture-password" }, null, true);
    await accounts.store.update(actor.id, { must_change_password: 0 });
    const permissions = projectPermissionCatalog.filter(entry => entry.scope === "project").map(entry => entry.id);
    const project = await database.client.project.create({ data: { name: "初始化重试", directoryName: "retry", directoryKey: "retry", ownerUserId: actor.id, remoteUrl: "https://example.test/repo.git" } });
    await database.client.projectMember.create({ data: { projectId: project.id, userId: actor.id, permissions } });
    const workspace = await database.client.workspace.create({ data: { name: "开发空间", ownerUserId: actor.id } });
    const account = await database.client.gitAccount.create({ data: { name: "测试 Git", userId: actor.id, authType: "http", remoteUrl: project.remoteUrl, host: "example.test", credentials: encodeSecret({ username: "fixture", password: "fixture" }, database.encryptionKey) } });
    await database.client.developmentSpace.create({ data: { projectId: project.id, userId: actor.id, workspaceId: workspace.id, gitAccountId: account.id, status: "ready" } });
    const repository = path.join(root, "repository"); fs.mkdirSync(repository);
    const git = (...args) => execFileSync("git", ["-C", repository, ...args], { windowsHide: true, stdio: "pipe" });
    git("init", "-b", "main");
    fs.writeFileSync(path.join(repository, "init.cjs"), 'const fs = require("node:fs"); fs.appendFileSync("attempts.txt", "attempt\\n"); if (!fs.existsSync("ready.txt")) process.exit(1);');
    git("add", "."); git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.test", "commit", "-m", "initial");
    const remote = path.join(root, "remote.git");
    execFileSync("git", ["clone", "--bare", repository, remote], { windowsHide: true, stdio: "pipe" });
    git("remote", "add", "origin", remote);
    await database.writeDocument(path.join(root, "system-settings.json"), { memberStorageRoot: path.join(root, "trees") });
    await database.writeWorkspace(workspace.id, { version: 6, workspace: { id: workspace.id, name: "开发空间", owner_user_id: actor.id, owner_username: actor.username, project_id: project.id }, agent: { provider: "codex" }, execution: { repository, projectName: project.directoryName, baseBranch: "main", initCommands: ["node init.cjs"] } });
    const client = new FakeClient();
    workspaces = new WorkspaceManager({ database, directory: path.join(root, "workspaces"), createManager: options => new SessionManager({ ...options, client }) });
    projects = new ProjectServices(database, { workspaces });
    workspaces.authorizeProject = (id, user, permission) => projects.workspaceAuthorization(id, user, permission);
    const content = new ProjectContentServices(database, projects);
    const services = new ProjectDevelopmentServices(database, projects, workspaces);
    const issue = await content.createIssue(project.id, actor, { type: "requirement", title: "重试初始化场景", description: "验证失败后重试", acceptanceCriteria: ["可以开始开发"], businessOwnerId: actor.id, qaOwnerId: actor.id, acceptanceOwnerId: actor.id });
    await database.client.projectIssue.update({ where: { id: issue.id }, data: { status: "planned" } });
    const planned = await services.create(project.id, actor, { requestId: randomUUID(), issueIds: [issue.id] });
    const started = await services.start(project.id, planned.tasks[0].id, actor, { requestId: randomUUID(), revision: planned.tasks[0].revision, baseBranch: "main" });
    const { sessions } = await workspaces.get(workspace.id, actor);
    await sessions.sessions.get(started.task.runKey).operation;
    const before = await sessions.store.read(started.task.runKey);
    assert.equal(before.initialization.status, "failed");
    assert.equal(client.calls.filter(call => call.method === "turn/start").length, 0);
    fs.writeFileSync(path.join(before.worktree.path, "ready.txt"), "resolved");
    application = createWebServer({ database, workspaces, dataDirectory: root });
    const origin = await application.listen(0);
    browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : process.platform === "win32" ? { channel: "msedge" } : {}) });
    const page = await browser.newPage({ locale: "zh-CN", viewport: { width: 1440, height: 900 } });
    await page.goto(origin);
    await page.getByLabel("账号", { exact: true }).fill("retry-admin");
    await page.getByLabel("密码", { exact: true }).fill("fixture-password");
    await page.getByRole("button", { name: "登录", exact: true }).click();
    await page.getByRole("heading", { name: "工作台", exact: true }).waitFor();
    await page.goto(`${origin}/projects/${project.id}?tab=tasks&task=${started.task.id}`);
    await page.getByRole("button", { name: "重试初始化并启动", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByText("将在原工作目录重新执行当前初始化命令，成功后启动 Agent。请先处理失败原因；命令可能修改目录中的文件。", { exact: true }).waitFor();
    const output = path.resolve("state/browser/initialization-retry-real"); fs.mkdirSync(output, { recursive: true });
    await page.screenshot({ path: path.join(output, "confirmation.png"), fullPage: true });
    await dialog.getByRole("button", { name: "确认重试并启动", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    const deadline = Date.now() + 15000;
    while (!client.calls.some(call => call.method === "turn/start") && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 50));
    assert.equal(client.calls.filter(call => call.method === "turn/start").length, 1);
    const after = await sessions.store.read(started.task.runKey);
    assert.deepEqual(after.worktree, before.worktree);
    assert.equal(fs.readFileSync(path.join(before.worktree.path, "attempts.txt"), "utf8"), "attempt\nattempt\n");
    console.log("Real PostgreSQL, Git, browser and initialization retry scenario passed.");
  } finally {
    await browser?.close(); await application?.close(); await workspaces?.close(); await projects?.close(); await accounts?.close(); await database.close();
    for (const callback of cleanup.reverse()) await callback();
  }
}
main().catch(error => { process.stderr.write(`${error.stack}\n`); process.exitCode = 1; });
