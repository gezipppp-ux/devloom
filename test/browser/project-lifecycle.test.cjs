const { selectOption, selectOptions } = require("../support/select.cjs");
const { openProjectTab } = require("../support/browser-navigation.cjs");
/* global document, window */
const assert = require("node:assert/strict");
const path = require("node:path");

async function verifyProjectLifecycle({ page, origin, project, database, output, projects, admin }) {
  const tab = name => openProjectTab(page, name);
  const releaseRow = page.getByRole('article', { name: 'v0.2', exact: true });
  const releaseName = releaseRow.getByRole('button', { name: '查看范围', exact: true });
  async function openRelease() { if (!(await page.locator('.release-scope-page').isVisible())) await releaseName.click(); }
  async function archiveVersion() {
    await openRelease();
    await page.getByRole("button", { name: "归档版本", exact: true }).click();
    await page.getByRole("dialog", { name: "归档版本", exact: true }).getByRole("button", { name: "确认归档版本", exact: true }).click();
  }
  await tab("版本");
  await page.getByRole("button", { name: "新建版本", exact: true }).click();
  await page.getByLabel("版本名称", { exact: true }).fill("v0.2");
  await page.getByLabel("版本说明", { exact: true }).fill("隔离数据库中的发布计划");
  await page.getByLabel("目标日期（可选）", { exact: true }).fill("2026-10-23");
  await page.getByRole("button", { name: "保存版本", exact: true }).click();
  await releaseName.waitFor();
  const plannedRelease = await database.client.projectRelease.findFirst({ where: { projectId: project.id, name: "v0.2" } });
  assert.equal(plannedRelease.targetDate.toISOString().slice(0, 10), "2026-10-23");
  assert.equal(await releaseRow.getByRole("progressbar", { name: "版本完成进度", exact: true }).count(), 0, "empty release never presents a false completion percentage");
  await openRelease();
  await page.getByRole("button", { name: "编辑版本", exact: true }).click();
  assert.equal(await page.getByLabel("目标日期（可选）", { exact: true }).inputValue(), "2026-10-23");
  await page.getByLabel("目标日期（可选）", { exact: true }).fill("");
  await page.getByRole("button", { name: "保存版本", exact: true }).click();
  await page.locator('.release-detail-aside').getByText('暂无目标日期', { exact: true }).waitFor();
  assert.equal((await database.client.projectRelease.findUnique({ where: { id: plannedRelease.id } })).targetDate, null);
  await archiveVersion();
  await releaseName.waitFor({ state: "hidden" });
  await page.getByRole("checkbox", { name: "包含已归档版本", exact: true }).check();
  await releaseName.click();
  await page.getByRole("button", { name: "恢复版本", exact: true }).click();
  await page.getByRole("button", { name: "编辑版本", exact: true }).waitFor();
  await page.getByRole('button', { name: '返回版本', exact: true }).first().click();
  assert.equal(await page.getByRole("navigation", { name: "项目功能" }).getByRole("button", { name: "流程", exact: true }).count(), 0);
  await page.getByLabel("账号导航").getByRole("button", { name: "管理中心", exact: true }).click();
  await page.getByRole("navigation", { name: "管理中心", exact: true }).getByRole("button", { name: "流程编排", exact: true }).click();
  await page.getByRole("button", { name: "规划中", exact: true }).click();
  const oldIssue = await database.client.projectIssue.findFirst({ where: { projectId: project.id, type: "requirement" } });
  await page.getByLabel("状态名称", { exact: true }).fill("需求规划");
  const selected = page.locator("svg g.selected");
  await selected.focus(); await selected.press("ArrowRight");
  await page.getByRole("button", { name: "校验并发布流程", exact: true }).click();
  await page.getByText("已发布 v2", { exact: true }).waitFor();
  const unchanged = await database.client.projectIssue.findUnique({ where: { id: oldIssue.id } });
  assert.equal(unchanged.workflowVersionId, oldIssue.workflowVersionId, "published flow cannot rewrite in-flight issues");
  await page.locator(".operation-message-close").evaluateAll(buttons => buttons.forEach(button => button.click()));
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `workflow page overflow at ${width}`);
    await page.getByRole("button", { name: "校验并发布流程", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, `system-workflow-editor-${width}.png`), fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const publishedFlowLoaded = page.waitForResponse(response => response.url().endsWith(`/projects/${project.id}/issue-workflows/requirement`) && response.status() === 200);
  await page.goto(`${origin}/projects/${project.id}?tab=issues`);
  await publishedFlowLoaded;
  const publishedStatuses = await selectOptions(page.getByLabel("事项状态", { exact: true }));
  assert.ok(publishedStatuses.some(option => option.label === "需求规划"), JSON.stringify(publishedStatuses));
  await require("../support/browser-navigation.cjs").openIssueCreate(page);
  await page.getByLabel("标题", { exact: true }).fill("版本规划事项");
  await selectOption(page.getByLabel("目标版本", { exact: true }), { label: "v0.2" });
  await page.getByRole("button", { name: "保存事项", exact: true }).click();
  await page.getByRole("heading", { name: "版本规划事项", exact: true }).waitFor();
  assert.equal(await page.getByRole("group", { name: "事项流程图", exact: true }).count(), 0);
  const sourceIssueUrl = page.url();
  const first = await database.client.projectIssue.findFirst({ where: { projectId: project.id, title: "版本规划事项" } });
  assert.notEqual(first.workflowVersionId, oldIssue.workflowVersionId, "new issues use the newly published system workflow");
  const other = (await projects.create(admin, { name: "复用系统流程的另一项目", remoteUrl: project.remoteUrl })).project;
  const otherFlowLoaded = page.waitForResponse(response => response.url().endsWith(`/projects/${other.id}/issue-workflows/requirement`) && response.status() === 200);
  await page.goto(`${origin}/projects/${other.id}?tab=issues`);
  await otherFlowLoaded;
  await page.getByRole("heading", { name: other.name, exact: true }).waitFor();
  assert.ok((await selectOptions(page.getByLabel("事项状态", { exact: true }))).some(option => option.label === "需求规划"));
  await require("../support/browser-navigation.cjs").openIssueCreate(page);
  await page.getByLabel("标题", { exact: true }).fill("跨项目系统流程事项");
  await page.getByRole("button", { name: "保存事项", exact: true }).click();
  await page.getByRole("heading", { name: "跨项目系统流程事项", exact: true }).waitFor();
  assert.equal(await page.getByRole("group", { name: "事项流程图", exact: true }).count(), 0);
  const second = await database.client.projectIssue.findFirst({ where: { projectId: other.id, title: "跨项目系统流程事项" } });
  assert.equal(second.workflowVersionId, first.workflowVersionId, "new issues across projects bind the same system workflow version");
  await page.goto(sourceIssueUrl);
  await page.getByRole("button", { name: "认领", exact: true }).click();
  await page.getByRole("button", { name: "确认认领", exact: true }).click();
  await page.getByRole("button", { name: "取消任务并释放认领", exact: true }).waitFor();
  const taskId = new URL(page.url()).searchParams.get("task");
  const task = await database.client.developmentTask.findUnique({ where: { id: taskId } });
  assert.equal(task.status, "planned"); assert.equal(task.runKey, null);
  await page.getByRole("button", { name: "编辑任务信息", exact: true }).click();
  await page.getByLabel("任务标题", { exact: true }).fill("调整后的开发计划");
  await page.getByRole("button", { name: "保存任务信息", exact: true }).click();
  await page.getByRole("heading", { name: "调整后的开发计划", exact: true }).waitFor();
  await page.getByRole("button", { name: "取消任务并释放认领", exact: true }).click();
  await page.getByRole("dialog", { name: "取消任务并释放认领", exact: true }).getByRole("button", { name: "确认取消任务", exact: true }).click();
  await page.getByText("任务：已取消", { exact: true }).waitFor();
  assert.equal((await database.client.developmentTask.findUnique({ where: { id: taskId } })).status, "cancelled");
  const issue = await database.client.projectIssue.findFirst({ where: { projectId: project.id, title: "版本规划事项" } });
  await page.goto(`${origin}/projects/${project.id}?tab=issues&issue=${issue.id}`);
  await selectOption(page.getByLabel("目标状态", { exact: true }), { label: "已拒绝 · 取消事项" });
  await page.getByLabel("原因", { exact: true }).fill("本版本取消实现");
  const transition = page.waitForResponse(response => response.url().endsWith(`/issues/${issue.id}/transition`) && response.request().method() === "POST");
  await page.getByRole("button", { name: "取消事项", exact: true }).click();
  assert.equal((await transition).status(), 200);
  await tab("版本");
  await archiveVersion();
  await releaseName.waitFor({ state: "hidden" });
  await page.goto(`${origin}/projects/${project.id}?tab=issues&issue=${issue.id}`);
  await page.getByText("版本已归档，内容只读。", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "编辑事项", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "认领", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "发表评论", exact: true }).count(), 0);
  await page.goto(`${origin}/projects/${project.id}?tab=issues`);
  await page.getByRole("button", { name: "查询", exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "版本规划事项", exact: true }).count(), 0);
  await page.getByRole("checkbox", { name: "包含归档事项", exact: true }).check();
  await page.getByRole("button", { name: "查询", exact: true }).click();
  await page.getByRole("button", { name: "版本规划事项", exact: true }).waitFor();
}

module.exports = { verifyProjectLifecycle };
