const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { randomUUID } = require("node:crypto");
const { chromium } = require("playwright");
const { temporary, png } = require("../support/helpers.cjs");
const { initializeTestDatabase } = require("../support/database.cjs");
const { installReviewWorkflow } = require("../support/workflow-fixture.cjs");
const { selectOption } = require("../support/select.cjs");
const { AccountServices } = require("../../src/application/account-services.cjs");
const { ProjectServices } = require("../../src/application/project-services.cjs");
const { ProjectContentServices } = require("../../src/application/project-content-services.cjs");
const { ProjectDevelopmentServices } = require("../../src/application/project-development-services.cjs");
const { SystemWorkflowServices } = require("../../src/application/system-workflow-services.cjs");
const { WorkspaceManager } = require("../../src/application/workspace-manager.cjs");
const { recommendedWorkflow } = require("../../src/domain/recommended-workflow.cjs");
const { projectPermissionCatalog } = require("../../src/domain/project-permissions.cjs");
const { createWebServer } = require("../../src/http/server.cjs");

async function main() {
  const cleanup = [], t = { after: callback => cleanup.push(callback) };
  const directory = temporary(t), database = await initializeTestDatabase(t, directory);
  const accounts = new AccountServices(database), projects = new ProjectServices(database);
  const admin = await accounts.create({ username: "admin", password: "fixture-password" }, null, true);
  await accounts.store.update(admin.id, { must_change_password: 0 });
  const permissions = projectPermissionCatalog.map(permission => permission.id);
  const department = (await projects.saveDepartment(admin, { name: "团队", permissions })).department;
  await accounts.store.update(admin.id, { departmentId: department.id });
  const project = (await projects.create(admin, { name: "送验队列真实场景", remoteUrl: "https://example.test/team/repo.git" })).project;
  await projects.saveMember(project.id, admin, { revision: 1, permissions: permissions.filter(id => id !== "project.create") }, admin.id);
  await installReviewWorkflow(database, recommendedWorkflow("requirement"));
  const content = new ProjectContentServices(database, projects);
  const development = new ProjectDevelopmentServices(database, projects);
  const imageId = randomUUID();
  const issue = await content.createIssue(project.id, admin, { type: "requirement", title: "不启动 Agent 的真实送验场景", description: `完成线下修改\n\n![事项示例](/api/projects/${project.id}/files/${imageId})`, attachments: [{ id: imageId, name: "示例.png", mimeType: "image/png", data: png.toString("base64") }], acceptanceCriteria: ["修改结果可以验证"], businessOwnerId: admin.id, qaOwnerId: admin.id, acceptanceOwnerId: admin.id });
  const { tasks: [task] } = await development.create(project.id, admin, { requestId: randomUUID(), issueIds: [issue.id] });
  const workspaces = new WorkspaceManager({ database, directory: path.join(directory, "workspaces") });
  const application = createWebServer({ database, workspaces, dataDirectory: directory });
  const origin = await application.listen(0);
  const output = path.resolve("state/browser/delivery-queue-real"); fs.mkdirSync(output, { recursive: true });
  let browser;
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : process.platform === "win32" ? { channel: "msedge" } : {}) });
    const context = await browser.newContext({ locale: "zh-CN", viewport: { width: 1440, height: 900 } });
    const page = await context.newPage();
    await page.goto(origin);
    await page.getByLabel("账号", { exact: true }).fill("admin");
    await page.getByLabel("密码", { exact: true }).fill("fixture-password");
    await page.getByRole("button", { name: "登录", exact: true }).click();
    await page.getByRole("heading", { name: "工作台", exact: true }).waitFor();
    async function capture(name) {
      await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true });
    }
    const queue = `${origin}/development?projectId=${project.id}`;
    await page.goto(queue);
    await page.getByRole("button", { name: task.title, exact: true }).waitFor();
    await capture("development");
    await page.getByRole("button", { name: task.title, exact: true }).click();
    await page.getByRole("button", { name: "线下处理", exact: true }).click();
    const dialog = page.getByRole("dialog");
    assert.equal(await dialog.getByLabel("交付标题", { exact: true }).count(), 0);
    assert.equal(await dialog.getByLabel("交付验证人", { exact: true }).count(), 0);
    await dialog.getByText("admin", { exact: true }).waitFor();
    await dialog.getByRole("button", { name: "问题修复", exact: true }).click();
    assert.match(await dialog.getByLabel("交付说明", { exact: true }).inputValue(), /修复内容/);
    await dialog.getByLabel("交付说明", { exact: true }).fill("线下修改完成，按验收标准核对。");
    await dialog.getByRole("button", { name: "线下处理", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    const delivery = await database.client.projectDeliverable.findFirstOrThrow({ where: { issueId: issue.id } });
    assert.equal(delivery.status, "pending");
    assert.equal(delivery.title, issue.title);
    assert.equal(delivery.reviewerId, admin.id);
    await page.goto(`${origin}/projects/${project.id}?tab=tasks&task=${task.id}`);
    const issueStatus = page.locator(".development-next .project-records li").filter({ hasText: issue.title });
    await issueStatus.waitFor();
    assert.match(await issueStatus.innerText(), /待验证.*验证人：admin/);
    await page.getByText("任务：等待验证", { exact: true }).waitFor();
    assert.equal((await database.client.developmentTask.findUniqueOrThrow({ where: { id: task.id } })).status, "planned");
    await capture("task-awaiting-review");
    const loaded = page.waitForResponse(response => response.url().includes("/api/workbench/tasks?") && response.status() === 200);
    await page.goto(queue);
    await page.getByRole("heading", { name: "开发", exact: true }).waitFor();
    await loaded;
    assert.equal(await page.getByRole("button", { name: task.title, exact: true }).count(), 0);
    await page.goto(`${origin}/issues?projectId=${project.id}`);
    await page.getByRole("button", { name: issue.title, exact: true }).waitFor();
    await capture("issues");
    await page.goto(`${origin}/deliveries?projectId=${project.id}`);
    await page.getByRole("button", { name: delivery.title, exact: true }).waitFor();
    await capture("deliveries");
    await page.getByRole("button", { name: delivery.title, exact: true }).click();
    await page.getByRole("button", { name: "退回修改", exact: true }).click();
    const returned = page.getByRole("dialog", { name: "退回修改", exact: true });
    assert.equal(await returned.getByRole("button", { name: "确认退回", exact: true }).isDisabled(), true);
    await returned.getByLabel("退回原因", { exact: true }).fill("需要补充结果");
    await returned.getByRole("button", { name: "确认退回", exact: true }).click();
    await page.getByText("已退回", { exact: true }).first().waitFor();
    await page.goto(queue);
    await page.getByRole("button", { name: task.title, exact: true }).waitFor();
    assert.equal(await database.client.run.count(), 0, "offline delivery never starts an Agent");
    const workflows = new SystemWorkflowServices(database, accounts, projects);
    let { workflow } = await workflows.readWorkflow("requirement", admin);
    const definition = structuredClone(workflow.draft);
    definition.nodes.find(node => node.id === "rework").id = "team_rework";
    for (const edge of definition.transitions) {
      if (edge.from === "rework") edge.from = "team_rework";
      if (edge.to === "rework") edge.to = "team_rework";
    }
    ({ workflow } = await workflows.saveWorkflow("requirement", admin, { revision: workflow.revision, definition }));
    await page.goto(`${origin}/system?tab=workflows`);
    await page.getByRole("button", { name: "校验并发布流程", exact: true }).first().click();
    const mapping = page.getByRole("dialog");
    await selectOption(mapping.getByLabel("待返工", { exact: true }), "team_rework");
    await capture("workflow-mapping");
    await mapping.getByRole("button", { name: "确认并发布", exact: true }).click();
    await mapping.waitFor({ state: "detached" });
    assert.equal((await content.readIssue(project.id, issue.id, admin)).status, "team_rework");
    await page.goto(queue);
    await page.getByRole("button", { name: task.title, exact: true }).click();
    await page.getByRole("button", { name: "重新提交验证", exact: true }).click();
    const resubmit = page.getByRole("dialog");
    await resubmit.getByLabel("交付说明", { exact: true }).fill("已补充验证结果。");
    await resubmit.getByRole("button", { name: "重新提交验证", exact: true }).click();
    await resubmit.waitFor({ state: "detached" });
    const latest = await database.client.projectDeliverable.findFirstOrThrow({ where: { issueId: issue.id, supersedesId: delivery.id } });
    await page.goto(`${origin}/deliveries?projectId=${project.id}&delivery=${latest.id}`);
    await page.getByRole("heading", { name: "验收核对", exact: true }).waitFor();
    await page.getByRole("heading", { name: "事项详情", exact: true }).waitFor();
    await page.getByText("完成线下修改", { exact: true }).waitFor();
    await page.getByRole("img", { name: "事项示例", exact: true }).waitFor();
    await capture("requirement-review");
    assert.equal(await page.getByRole("button", { name: "开始验证", exact: true }).count(), 0);
    await page.getByRole("button", { name: "一键全选", exact: true }).click();
    await page.getByRole("button", { name: "验证通过", exact: true }).click();
    await page.getByText("已通过", { exact: true }).first().waitFor();
    assert.equal((await content.readIssue(project.id, issue.id, admin)).status, "implemented");
    assert.equal((await database.client.projectDeliverable.findUniqueOrThrow({ where: { id: latest.id } })).reviewNote, "");
    const issuesLoaded = page.waitForResponse(response => response.url().includes("/api/workbench/issues?") && response.status() === 200);
    await page.goto(`${origin}/issues?projectId=${project.id}`);
    await issuesLoaded;
    assert.equal(await page.getByRole("button", { name: issue.title, exact: true }).count(), 0);
    await page.getByRole("button", { name: "查看全部事项", exact: true }).click();
    await page.getByRole("button", { name: issue.title, exact: true }).waitFor();
    ({ workflow } = await workflows.readWorkflow("requirement", admin));
    const broken = structuredClone(workflow.draft);
    broken.transitions = broken.transitions.filter(edge => !(edge.from === "team_rework" && ["development.assigned", "development.started", "delivery.submitted"].includes(edge.trigger)));
    await workflows.saveWorkflow("requirement", admin, { revision: workflow.revision, definition: broken });
    await page.goto(`${origin}/system?tab=workflows`);
    await page.getByRole("button", { name: "校验并发布流程", exact: true }).first().click();
    await page.getByText("验证退回后必须能够继续处理并重新送验。", { exact: true }).waitFor();
    assert.equal((await workflows.readWorkflow("requirement", admin)).workflow.publishedVersion, workflow.publishedVersion);
    await installReviewWorkflow(database, recommendedWorkflow("bug"), "bug");
    const bug = await content.createIssue(project.id, admin, { type: "bug", title: "导出结果错误", description: "筛选后导出不一致", reproductionSteps: "筛选客户并导出", expectedResult: "导出匹配筛选条件", actualResult: "导出包含其他客户", businessOwnerId: admin.id, qaOwnerId: admin.id, acceptanceOwnerId: admin.id });
    const { tasks: [bugTask] } = await development.create(project.id, admin, { requestId: randomUUID(), issueIds: [bug.id] });
    const bugDelivery = await content.addDeliverable(project.id, admin, { requestId: randomUUID(), issueId: bug.id, taskId: bugTask.id, body: "修复导出筛选" });
    await page.goto(`${origin}/deliveries?projectId=${project.id}&delivery=${bugDelivery.id}`);
    const issueDetails = page.locator(".delivery-detail-main .delivery-section").first();
    for (const text of ["筛选客户并导出", "导出匹配筛选条件", "导出包含其他客户"]) await issueDetails.getByText(text, { exact: true }).waitFor();
    await capture("bug-review");
    await page.getByRole("button", { name: "一键全选", exact: true }).click();
    await page.getByRole("button", { name: "验证通过", exact: true }).click();
    await page.getByText("已通过", { exact: true }).first().waitFor();
    assert.equal((await content.readIssue(project.id, bug.id, admin)).status, "verified");
    console.log("Real delivery queue browser scenario passed.");
  } finally {
    await browser?.close(); await application.close(); await projects.close(); await accounts.close(); await database.close();
    for (const callback of cleanup.reverse()) await callback();
  }
}
main().catch(error => { process.stderr.write(`${error.stack}\n`); process.exitCode = 1; });
