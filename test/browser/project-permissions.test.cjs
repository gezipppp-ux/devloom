/* global document, window */
const assert = require("node:assert/strict");
const path = require("node:path");
const { productTemplate } = require("../../src/domain/project-permissions.cjs");

async function verifyProjectPermissions({ page, projects, accounts, admin, project, output }) {
  const department = (await projects.saveDepartment(admin, { name: "权限预览测试部门", permissions: productTemplate })).department;
  const user = await accounts.create({ username: "permission-preview", password: "fixture-password", departmentId: department.id }, admin);
  await page.reload();
  await page.getByRole("navigation", { name: "项目功能" }).getByRole("button", { name: "成员", exact: true }).click();
  await page.getByRole("heading", { name: "项目成员", exact: true }).waitFor();
  await page.getByRole("button", { name: "添加成员", exact: true }).click();
  await page.getByRole("dialog", { name: "添加成员", exact: true }).waitFor();
  const select = page.getByLabel("用户", { exact: true });
  await select.selectOption(user.id);
  assert.equal(await page.getByRole("button", { name: "保存成员", exact: true }).isEnabled(), true, "new members receive project visibility");
  await page.getByText('权限组合与高级设置', { exact: true }).click();
  await page.getByLabel("权限组合", { exact: true }).selectOption("agent");
  await page.getByText(/部门未开放：.*启动开发任务/).waitFor();
  assert.equal(await page.getByRole("button", { name: "添加Agent 开发组合", exact: true }).isDisabled(), true, "a blocked core capability cannot masquerade as a successful combination");
  await page.getByText('筛选与批量操作', { exact: true }).click();
  await page.getByRole("navigation", { name: "权限分类" }).getByRole("button", { name: "开发", exact: true }).click();
  assert.equal(await page.getByRole("checkbox", { name: "认领并启动开发任务", exact: true }).isDisabled(), true, "detail editing respects the department ceiling");
  assert.equal(await page.getByRole("checkbox", { name: "本组全选", exact: true }).isDisabled(), true, "bulk selection cannot bypass the department ceiling");
  await page.getByLabel("权限组合", { exact: true }).selectOption("product");
  await page.getByRole("button", { name: "添加产品协作组合", exact: true }).click();
  await page.getByText(/保存后实际可用功能：/).waitFor();
  assert.equal((await page.getByText(/保存后实际可用功能：/).textContent()).includes("启动开发任务"), false);
  await page.getByRole("button", { name: "保存成员", exact: true }).click();
  await page.getByRole("button", { name: "调整permission-preview（permission-preview）权限", exact: true }).waitFor();
  assert.equal(await select.locator(`option[value="${user.id}"]`).count(), 0, "active member is excluded from add candidates");
  await page.getByRole("button", { name: "调整permission-preview（permission-preview）权限", exact: true }).click();
  await page.getByText('成员状态与授权说明', { exact: true }).click();
  await page.getByLabel("成员状态", { exact: true }).selectOption("disabled");
  await page.getByRole("button", { name: "保存成员", exact: true }).click();
  await page.getByRole("button", { name: "恢复permission-preview（permission-preview）成员", exact: true }).waitFor();
  assert.equal(await select.locator(`option[value="${user.id}"]`).count(), 0, "historical member has an explicit restore action");
  await page.getByRole("button", { name: "恢复permission-preview（permission-preview）成员", exact: true }).click();
  assert.equal(await page.getByLabel("成员状态", { exact: true }).inputValue(), "active");
  await page.getByRole("button", { name: "保存成员", exact: true }).click();
  await page.getByRole("button", { name: "调整permission-preview（permission-preview）权限", exact: true }).waitFor();
  assert.equal((await projects.members(project.id, admin)).members.filter(member => member.userId === user.id).length, 1);
  await page.getByRole("button", { name: "调整admin（admin）权限", exact: true }).click();
  assert.equal(await page.locator(".project-permission-editor").count(), 0, "administrators require no permission editor");
  await page.getByText("管理员不属于任何部门，自动拥有全部权限，无需分配。", { exact: true }).waitFor();
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: path.join(output, `permissions-${width}.png`), fullPage: true });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    assert.equal(overflow, false, `permissions page fits ${width}px`);
  }
  await page.getByRole("button", { name: "取消", exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
}
async function verifyDepartmentCapabilities({ page, output }) {
  await page.getByRole("button", { name: "新建部门", exact: true }).click();
  await page.getByRole("heading", { name: "部门可用功能", exact: true }).waitFor();
  assert.equal(await page.getByLabel("权限组合", { exact: true }).count(), 0, "department configuration is a capability ceiling, not project work assignments");
  const cards = page.locator(".permission-capabilities");
  assert.equal(await cards.getByRole("checkbox").count(), 6);
  await cards.getByRole("checkbox", { name: "Agent 开发", exact: true }).check();
  assert.equal(await cards.getByRole("checkbox", { name: "代码操作", exact: true }).isChecked(), true, "department capabilities include required code access");
  await cards.getByRole("checkbox", { name: "代码操作", exact: true }).uncheck();
  assert.equal(await cards.getByRole("checkbox", { name: "Agent 开发", exact: true }).isChecked(), false, "removing required capability also removes dependent execution");
  const editor = page.locator(".project-permission-editor");
  const categories = editor.getByRole("navigation", { name: "权限分类" });
  const search = editor.getByRole("searchbox", { name: "搜索权限", exact: true });
  const revert = editor.getByRole("button", { name: "撤销权限修改", exact: true });
  await revert.click();
  assert.equal(await editor.locator(".permission-details").evaluate(element => element.open), true, "department details are open by default");
  assert.equal(await categories.getByRole("button").count(), 7);
  await editor.getByRole("checkbox", { name: "只看已开放", exact: true }).check();
  await editor.getByText("尚未选择任何权限", { exact: true }).waitFor();
  await editor.getByRole("button", { name: "清除筛选", exact: true }).click();
  await search.fill("启动");
  assert.equal(await editor.locator(".permission-detail-row").count(), 1);
  await editor.getByRole("checkbox", { name: "全选筛选结果", exact: true }).check();
  await editor.getByText("待保存：新增 5 项 · 取消 0 项", { exact: true }).waitFor();
  assert.match(await editor.getByRole("status").textContent(), /自动补齐[:：]\s*.*查看项目/);
  await search.fill("");
  await categories.getByRole("button", { name: "Agent", exact: true }).click();
  assert.equal(await editor.getByRole("checkbox", { name: "继续对话", exact: true }).isChecked(), false, "filtered bulk selection leaves hidden permissions unchanged");
  await categories.getByRole("button", { name: "代码", exact: true }).click();
  await editor.getByRole("checkbox", { name: "执行仓库操作", exact: true }).uncheck();
  assert.match(await editor.getByRole("status").textContent(), /联动关闭[:：]\s*认领并启动开发任务/);
  await categories.getByRole("button", { name: "Agent", exact: true }).click();
  assert.equal(await editor.getByRole("checkbox", { name: "认领并启动开发任务", exact: true }).isChecked(), false);
  await revert.click();
  await categories.getByRole("button", { name: "项目", exact: true }).click();
  await editor.getByRole("checkbox", { name: "本组全选", exact: true }).check();
  await editor.getByRole("checkbox", { name: "修改项目配置", exact: true }).uncheck();
  assert.equal(await editor.getByRole("checkbox", { name: "创建项目", exact: true }).isChecked(), false);
  assert.equal(await editor.getByRole("checkbox", { name: "本组全选", exact: true }).evaluate(element => element.indeterminate), true);
  await editor.getByRole("button", { name: "清空本组", exact: true }).click();
  assert.equal(await revert.isDisabled(), true);
  await search.fill("不存在的权限");
  await editor.getByText("没有匹配的权限", { exact: true }).waitFor();
  await editor.getByRole("button", { name: "清除筛选", exact: true }).click();
  await categories.getByRole("button", { name: "需求与 Bug", exact: true }).click();
  await editor.getByRole("checkbox", { name: "编辑需求与 Bug", exact: true }).check();
  await page.getByLabel("部门名称", { exact: true }).fill("分类双栏回归部门");
  await search.fill("编辑");
  await search.press("Enter");
  assert.equal(await page.getByRole("button", { name: "保存部门", exact: true }).isEnabled(), true, "Enter in permission search does not submit the department form");
  await search.fill("");
  let resumeSave, markSaving;
  const saving = new Promise(resolve => { markSaving = resolve; });
  const release = new Promise(resolve => { resumeSave = resolve; });
  const saveRoute = async route => { if (route.request().method() === "POST") { markSaving(); await release; } await route.continue(); };
  await page.route("**/api/admin/departments", saveRoute);
  await page.getByRole("button", { name: "保存部门", exact: true }).click();
  await saving;
  try {
    assert.equal(await editor.getByRole("checkbox", { name: "编辑需求与 Bug", exact: true }).isDisabled(), true);
    assert.equal(await revert.isDisabled(), true);
    assert.equal(await editor.getByRole("checkbox", { name: "本组全选", exact: true }).isDisabled(), true);
  } finally { resumeSave(); }
  const editSaved = page.getByRole("button", { name: "编辑分类双栏回归部门", exact: true });
  await editSaved.waitFor();
  await page.unroute("**/api/admin/departments", saveRoute);
  await editSaved.click();
  assert.equal(await revert.isDisabled(), true, "loading a saved department establishes the comparison baseline");
  await categories.getByRole("button", { name: "项目", exact: true }).click();
  await editor.getByRole("checkbox", { name: "查看项目", exact: true }).uncheck();
  await editor.getByText("待保存：新增 0 项 · 取消 3 项", { exact: true }).waitFor();
  await revert.click();
  await categories.getByRole("button", { name: "需求与 Bug", exact: true }).click();
  assert.equal(await editor.getByRole("checkbox", { name: "编辑需求与 Bug", exact: true }).isChecked(), true, "reverting restores saved dependencies as well as the selected action");
  await search.fill("不应跨部门保留的筛选");
  await page.getByRole("button", { name: "编辑研发与产品", exact: true }).click();
  assert.equal(await search.inputValue(), "");
  assert.equal(await revert.isDisabled(), true);
  assert.equal(await editor.getByRole("status").count(), 0, "switching departments clears old feedback");
  await categories.getByRole("button", { name: "Agent", exact: true }).click();
  await page.locator(".operation-message-close").evaluateAll(buttons => buttons.forEach(button => button.click()));
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: path.join(output, `department-capabilities-${width}.png`), fullPage: true });
    await editor.locator(".permission-details").screenshot({ path: path.join(output, `department-details-${width}.png`) });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    const row = editor.locator(".permission-detail-row").first();
    const inputBox = await row.locator("input").boundingBox(), labelBox = await row.locator(".permission-label").boundingBox();
    assert.ok(inputBox.x + inputBox.width <= labelBox.x && Math.abs(inputBox.y - labelBox.y) < 12, `checkbox and label remain on the same row at ${width}px`);
    const navigationBox = await categories.boundingBox(), paneBox = await editor.locator(".permission-pane").boundingBox();
    assert.ok(width > 600 ? navigationBox.x + navigationBox.width <= paneBox.x + 1 : navigationBox.y + navigationBox.height <= paneBox.y + 1, `permission categories reflow at ${width}px`);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
}
module.exports = { verifyProjectPermissions, verifyDepartmentCapabilities };
