async function addUser(database, name, role = "member") {
  return database.client.user.create({ data: { username: name, displayName: name, passwordHash: "fixture-hash", role } });
}

test("explicit nested data roots initialize independently from parent resource routing", async (t) => {
  let parent;
  let nested;
  t.after(async () => { await nested?.close(); await parent?.close(); });
  const root = temporary(t);
  const nestedRoot = path.join(root, "cache", "independent-data");
  parent = await initializeTestDatabase(t, root);
  nested = await initializeTestDatabase(t, nestedRoot);
  assert.notEqual(nested, parent);
  assert.equal(nested.dataRoot, nestedRoot);
  assert.equal(fs.existsSync(path.join(nestedRoot, "db", "web-coding.sqlite")), false);
  await addUser(parent, "parent-member");
  await addUser(nested, "nested-member");
  assert.deepEqual(await parent.client.user.findMany({ select: { username: true } }), [{ username: "parent-member" }]);
  assert.deepEqual(await nested.client.user.findMany({ select: { username: true } }), [{ username: "nested-member" }]);
  const nestedSettings = path.join(nestedRoot, "system-settings.json");
  assert.equal(databaseForPath(nestedSettings), nested);
  assert.equal(await initializeTestDatabase(t, nestedRoot), nested);
});

test("PostgreSQL initializes once, skips old files, encrypts credentials and isolates member workspaces", async (t) => {
  let database;
  let reopened;
  t.after(async () => { await database?.close(); await reopened?.close(); });
  const root = temporary(t);
  const staleId = randomUUID();
  const old = path.join(root, "workspaces", staleId, "config.json");
  fs.mkdirSync(path.dirname(old), { recursive: true });
  fs.writeFileSync(old, JSON.stringify({ workspace: { id: staleId, name: "不会导入" } }));
  const results = await Promise.all([initializeTestDatabase(t, root), initializeTestDatabase(t, root)]);
  [database] = results;
  const concurrent = results[1];
  assert.equal(database, concurrent);
  assert.equal(databaseForPath(old), database);
  assert.equal((await readOptional(old)).workspace, undefined);
  assert.equal(await database.client.user.count(), 0);
  const alice = await addUser(database, "alice");
  const bob = await addUser(database, "bob");
  const admin = await addUser(database, "admin", "admin");
  const workspaces = new WorkspaceManager({ directory: path.join(root, "workspaces") });
  const first = (await workspaces.save({ name: "同名项目" }, undefined, alice));
  const second = (await workspaces.save({ name: "同名项目" }, undefined, bob));
  assert.notEqual(first.id, second.id);
  assert.deepEqual((await workspaces.list(alice)).map(({ id }) => id), [first.id]);
  (await assert.rejects(async () => (await workspaces.list()), /登录/));
  (await assert.rejects(async () => (await workspaces.read(first.id, bob)), /不存在/));
  (await assert.rejects(async () => (await workspaces.read(first.id, admin)), /不存在/));
  (await assert.rejects(async () => (await workspaces.save({ name: "同名项目" }, undefined, alice)), /已存在/));
  (await assert.rejects(async () => (await workspaces.save({ name: "越权" }, first.id, bob)), /不存在/));
  const file = workspaces.configFile(first.id);
  (await updateConfig(file, (config) => ({ ...config, workspace: { ...config.workspace, owner_username: "bob" }, tapd: { session: { cookie_header: "private-cookie" } } })));
  assert.equal((await readOptional(file)).tapd.session.cookie_header, "private-cookie");
  assert.equal((await database.readWorkspace(first.id, alice.id)).workspace.owner_username, "alice");
  assert.equal((await readOptional(file)).workspace.owner_username, "alice", "stored configuration cannot replace the owning account name");
  assert.equal((await database.readWorkspace(second.id, bob.id)).workspace.owner_username, "bob");
  const serialized = JSON.stringify((await database.client.workspaceSetting.findUniqueOrThrow({ where: { workspaceId: first.id } })).data);
  assert.equal(serialized.includes("private-cookie"), false);
  assert.equal(fs.existsSync(file), false);
  const settingsFile = path.join(root, "system-settings.json");
  (await writeConfig(settingsFile, { memberStorageRoot: root }));
  const effective = (await executionConfig((await readOptional(file)), file));
  assert.equal(effective.execution.worktreeRoot, path.join(root, "alice", "worktree", "w-" + first.id.slice(0, 8)));
  assert.equal((await readSettings(file)).memberRoot, path.join(root, "alice"));
  const missingUsername = structuredClone((await readOptional(file)));
  delete missingUsername.workspace.owner_username;
  (await assert.rejects(async () => (await executionConfig(missingUsername, file)), /账号|用户|所有者/));
  await database.close();
  reopened = await initializeTestDatabase(t, root);
  assert.equal((await readOptional(file)).tapd.session.cookie_header, "private-cookie");
  assert.equal((await readOptional(file)).workspace.owner_username, "alice");
  assert.equal((await readSettings(file)).memberRoot, path.join(root, "alice"));
  assert.equal((await readOptional(settingsFile)).memberStorageRoot, root);
  assert.equal(reopened.ready, true);
});

test("database documents, run projections and binary attachments remain authoritative without disk files", async (t) => {
  let database;
  t.after(() => database?.close());
  const root = temporary(t);
  database = await initializeTestDatabase(t, root);
  const actor = await addUser(database, "member");
  const workspaces = new WorkspaceManager({ directory: path.join(root, "workspaces") });
  const workspace = (await workspaces.save({ name: "存储测试" }, undefined, actor));
  const directory = path.join(root, "workspaces", workspace.id, "runs", "1-2");
  const file = path.join(directory, "run.json");
  (await writeConfig(file, { agent: { provider: "codex" }, source: { channel: "tapd", scope: "1", id: "2" }, session_id: "session-id", status: "running" }));
  (await updateConfig(file, (value) => ({ ...value, status: "finished" })));
  const row = await database.client.run.findFirstOrThrow();
  assert.equal(row.ownerUserId, actor.id);
  assert.equal(row.executionState, "finished");
  assert.equal(row.sessionId, "session-id");
  const snapshot = path.join(directory, "requirement.json");
  (await writeConfig(snapshot, { title: "保留资料" }));
  assert.equal((await database.listDocuments(directory)).length, 2);
  const image = path.join(directory, "images", "1.png");
  (await database.putBlob(image, png, { mimeType: "image/png", expiresAt: "2030-01-01T00:00:00.000Z" }));
  assert.deepEqual((await database.readBlob(image)).data, png);
  assert.equal((await database.listBlobs(directory))[0].path, image);
  assert.equal(fs.existsSync(directory), false);
  await assert.rejects(() => database.readDocument(path.join(root, "..", "outside.json")), /当前数据目录/);
  assert.equal((await database.deleteDocument(snapshot)), true);
  assert.equal((await database.readDocument(snapshot)), undefined);
  assert.equal((await database.deleteBlob(image)), true);
});

test("existing PostgreSQL refuses missing or mismatched encryption keys without changing persisted data", async (t) => {
  const root = temporary(t);
  const database = await initializeTestDatabase(t, root);
  const marker = await database.client.authMetadata.findUniqueOrThrow({ where: { name: "encryption-key-fingerprint" } });
  await database.close();
  const keyFile = path.join(root, "secrets", "database.key");
  const original = fs.readFileSync(keyFile);
  fs.unlinkSync(keyFile);
  await assert.rejects(initializeTestDatabase(t, root), /主密钥缺失/);
  assert.equal(fs.existsSync(keyFile), false);
  fs.writeFileSync(keyFile, Buffer.alloc(32, 7));
  await assert.rejects(initializeTestDatabase(t, root), /不匹配/);
  assert.equal(databaseForPath(root), undefined);
  fs.writeFileSync(keyFile, original);
  const reopened = await initializeTestDatabase(t, root);
  assert.equal((await reopened.client.authMetadata.findUniqueOrThrow({ where: { name: marker.name } })).value, marker.value);
});

test("connection errors never fall back to or modify legacy SQLite and JSON data", async (t) => {
  const root = temporary(t);
  const oldDatabase = path.join(root, "db", "web-coding.sqlite");
  const oldSettings = path.join(root, "system-settings.json");
  fs.mkdirSync(path.dirname(oldDatabase), { recursive: true });
  fs.writeFileSync(oldDatabase, "legacy SQLite sentinel");
  fs.writeFileSync(oldSettings, '{"legacy":true}');
  await assert.rejects(initializeDatabase(root, { url: "postgresql://fixture:secret@127.0.0.1:1/unavailable" }), (error) => {
    assert.match(error.message, /PostgreSQL/);
    assert.doesNotMatch(error.message, /fixture:secret/);
    return true;
  });
  assert.equal(databaseForPath(oldSettings), undefined);
  assert.equal(fs.readFileSync(oldDatabase, "utf8"), "legacy SQLite sentinel");
  assert.equal(fs.readFileSync(oldSettings, "utf8"), '{"legacy":true}');
  const database = await initializeTestDatabase(t, root);
  assert.equal((await readOptional(oldSettings)).legacy, undefined);
  assert.equal(await database.client.user.count(), 0);
  assert.equal(fs.readFileSync(oldDatabase, "utf8"), "legacy SQLite sentinel");
  assert.equal(fs.readFileSync(oldSettings, "utf8"), '{"legacy":true}');
  assert.equal(fs.existsSync(path.join(root, "db", "backups")), false);
});

