for (const databaseMode of [false, true]) test(`immutable previews, compare-and-swap and run isolation (${databaseMode ? "PostgreSQL" : "file fixture"})`, async t => {
  let database;
  t.after(() => database?.close());
  const directory = temporary(t), worktree = temporary(t);
  if (databaseMode) database = await initializeTestDatabase(t, directory);
  const file = path.join(worktree, "mock.html");
  const store = new SessionPreviewStore(path.join(directory, "runs", "1-2"));
  fs.writeFileSync(file, "<h1>Original</h1>");
  const capture = { itemId: "reply", turnId: "one", reference: { path: file, title: "Preview" }, ordinal: 0, worktree };
  const first = await store.capture(capture);
  fs.writeFileSync(file, "<h1>Changed</h1>");
  assert.equal((await store.capture(capture)).id, first.id);
  assert.equal(await store.content(first.id), "<h1>Original</h1>");
  const state = { widget: { modelContent: { count: 1 }, privateContent: { secret: "hidden" } }, controls: { radius: 12 } };
  const saves = await Promise.allSettled([store.save(first.id, 0, state), store.save(first.id, 0, state)]);
  assert.equal(saves.filter(result => result.status === "fulfilled").length, 1);
  assert.equal(saves.find(result => result.status === "rejected").reason.statusCode, 409);
  const reopened = new SessionPreviewStore(path.join(directory, "runs", "1-2"));
  assert.deepEqual((await reopened.read(first.id)).state, state);
  const second = await reopened.capture({ ...capture, itemId: "next", turnId: "two" });
  assert.equal(second.version, 2);
  await assert.rejects(store.save(first.id, 1, state), { statusCode: 409 });
  assert.equal((await store.read(first.id)).latest, false);
  fs.unlinkSync(file);
  assert.equal(await reopened.content(second.id), "<h1>Changed</h1>");
  const foreign = new SessionPreviewStore(path.join(directory, "runs", "1-3"));
  await assert.rejects(foreign.read(first.id), { statusCode: 404 });
  const outside = path.join(directory, "outside.html");
  fs.writeFileSync(outside, "<p>outside</p>");
  await assert.rejects(store.capture({ ...capture, itemId: "bad", reference: { path: outside } }), /当前任务/);
  fs.writeFileSync(file, "x".repeat(1024 * 1024 + 1));
  await assert.rejects(store.capture({ ...capture, itemId: "big" }), /1 MiB/);
  const alias = path.join(worktree, "linked");
  fs.symlinkSync(directory, alias, process.platform === "win32" ? "junction" : "dir");
  await assert.rejects(store.capture({ ...capture, itemId: "link", reference: { path: path.join(alias, "outside.html") } }), /当前任务|符号链接/);
});

test("presentation captures completed replies in place; feedback omits private state and validates membership", async t => {
  const directory = temporary(t), store = new RunStore(directory), key = "1-2";
  fs.mkdirSync(store.dir(key));
  fs.writeFileSync(path.join(store.dir(key), "run.json"), JSON.stringify({ worktree: { path: directory } }));
  const file = path.join(directory, "mock.html");
  fs.writeFileSync(file, "<b>Preview</b>");
  const presenter = new SessionPresenter({ store });
  const item = normalizeItem({ id: "message", type: "agentMessage", status: "inProgress", text: `Beforevisualize${JSON.stringify({ path: file })}After` }, "one");
  assert.equal((await presenter.item(key, item)).contentParts, undefined);
  const result = await presenter.item(key, { ...item, status: "completed" });
  assert.deepEqual(result.contentParts.map(part => part.type), ["text", "preview", "text"]);
  assert.equal(result.contentParts[0].text, "Before");
  assert.equal(result.contentParts[2].text, "After");
  assert.equal(JSON.stringify(result).includes(file), false);
  fs.writeFileSync(file, "<b>Unrelated later content</b>");
  const historical = await presenter.item(key, { ...item, id: "old-unobserved", status: "completed" }, "old", { capturePreviews: false });
  assert.equal(historical.contentParts[1].type, "preview-error");
  assert.equal((await store.previews(key).read(result.contentParts[1].id)).version, 1);
  const restored = await presenter.item(key, { ...item, status: "completed" }, "one", { capturePreviews: false });
  assert.equal(restored.contentParts[1].id, result.contentParts[1].id);
  assert.equal(await store.previews(key).content(result.contentParts[1].id), "<b>Preview</b>");
  const previews = new SessionPreviews({ store });
  const reference = { id: result.contentParts[1].id, state: { widget: { modelContent: "visible", privateContent: "SECRET" }, controls: {} } };
  const feedback = await previews.feedback(key, reference);
  assert.match(feedback, /visible/);
  assert.doesNotMatch(feedback, /SECRET|privateContent/);
  await assert.rejects(previews.feedback("1-3", reference), { statusCode: 404 });
});

test("preview HTTP fences CSRF, origins, lifecycle and explicit followup on the original session", async t => {
  const directory = temporary(t), store = new RunStore(directory), key = "1-2", client = new FakeClient();
  fs.mkdirSync(store.dir(key));
  fs.writeFileSync(path.join(store.dir(key), "run.json"), JSON.stringify({
    workitem: { id: "2", workspace_id: "1", title: "Preview" }, source: { channel: "manual", scope: "1", id: "2" },
    agent: { provider: "codex" }, session_id: "original", worktree: { path: directory, branch: "codex/fixture" }, execution: { status: "completed" },
  }));
  const manager = new SessionManager({ store, client, worktreeReason: () => null });
  const application = createWebServer({ manager, testIdentity: true });
  t.after(() => application.close());
  const origin = await application.listen(0), file = path.join(directory, "fixture.html");
  fs.writeFileSync(file, "<p>Only in sandbox</p>");
  const entry = await store.previews(key).capture({ itemId: "one", turnId: "one", ordinal: 0, reference: { path: file }, worktree: directory });
  const endpoint = `${origin}/api/runs/${key}/previews/${entry.id}`;
  const content = await fetch(endpoint + "/content");
  assert.equal(content.status, 200);
  assert.match(content.headers.get("content-security-policy"), /sandbox allow-scripts/);
  assert.doesNotMatch(content.headers.get("content-security-policy"), /allow-same-origin/);
  assert.match(content.headers.get("content-security-policy"), /connect-src 'none'/);
  assert.match(await content.text(), /Only in sandbox/);
  const state = { widget: { modelContent: "SHARED", privateContent: "PRIVATE" }, controls: { radius: 10 } };
  const post = (url, body, headers = {}) => fetch(url, { method: "POST", headers: { "content-type": "application/json", origin, ...headers }, body: JSON.stringify(body) });
  assert.equal((await post(endpoint + "/state", { revision: 0, state })).status, 403);
  const { token } = await (await fetch(`${origin}/api/bootstrap`)).json();
  const headers = { "x-csrf-token": token };
  assert.equal((await post(endpoint + "/state", { revision: 0, state }, headers)).status, 200);
  assert.equal(client.calls.length, 0, "saving does not connect or dispatch the Agent");
  assert.equal((await post(endpoint + "/state", { revision: 0, state }, headers)).status, 409);
  const sent = await post(`${origin}/api/runs/${key}/messages`, { text: "Continue", preview: { id: entry.id, state } }, headers);
  assert.equal(sent.status, 202, await sent.text());
  const call = client.calls.find(call => call.method === "turn/start");
  assert.equal(call.params.threadId, "original");
  assert.match(call.params.input[0].text, /SHARED/);
  assert.doesNotMatch(call.params.input[0].text, /PRIVATE|privateContent/);
  await store.archive(key);
  assert.equal((await post(endpoint + "/state", { revision: 1, state }, headers)).status, 409);
  assert.equal((await fetch(endpoint + "/content")).status, 200);
});
